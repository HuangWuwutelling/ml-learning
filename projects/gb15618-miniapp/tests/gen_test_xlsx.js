/**
 * 生成测试 xlsx：10 行混合风险等级 + 1 行错误
 */
const ExcelJS = require('exceljs');

async function main() {
  const wb = new ExcelJS.Workbook();
  const ws = wb.addWorksheet('Sheet1');
  ws.addRow(['sampleId', 'crop', 'pH', 'Cd', 'Hg', 'As', 'Pb', 'Cr', 'Cu', 'Zn', 'Ni']);

  // 4 行优先保护（Pi < 1）
  ws.addRow(['S001', '水田', 5.5, 0.1, 0.02, 3, 10, 30, 20, 50, 20]);
  ws.addRow(['S002', '旱地', 6.0, 0.2, 0.5, 10, 30, 100, 30, 100, 50]);
  ws.addRow(['S003', '果园', 6.5, 0.2, 1.0, 20, 50, 100, 100, 150, 50]);
  ws.addRow(['S004', '水田', 7.5, 0.5, 0.4, 15, 100, 200, 60, 150, 80]);

  // 3 行安全利用（超筛选但未超管制）
  ws.addRow(['S005', '水田', 5.5, 0.8, 0.3, 20, 50, 150, 30, 100, 50]);  // Cd 0.8/0.3=2.67 > 1, 0.8/1.5=0.53 ≤ 1
  ws.addRow(['S006', '旱地', 6.0, 0.25, 1.5, 30, 80, 130, 40, 180, 80]);  // Hg 1.5/1.8=0.83, Cd 0.25/0.3=0.83, 多个略超
  ws.addRow(['S007', '水田', 6.0, 0.4, 0.5, 25, 120, 250, 40, 150, 80]);

  // 2 行严格管控（超管制）
  ws.addRow(['S008', '水田', 5.5, 5.0, 0.5, 30, 100, 300, 30, 100, 50]);  // Cd 5/1.5=3.33 > 1
  ws.addRow(['S009', '旱地', 5.0, 2.0, 3.5, 200, 500, 1000, 80, 250, 200]);  // 多金属超标

  // 1 行 Cu/Ni 大幅超标但无控制值 → 应判到安全利用
  ws.addRow(['S010', '果园', 6.0, 0.2, 1.0, 15, 50, 100, 1000, 300, 500]);

  // 1 行错误：pH 缺失
  ws.addRow(['S011', '水田', '', 0.3, 0.5, 30, 80, 250, 50, 200, 60]);

  // 1 行错误：crop 非法
  ws.addRow(['S012', '森林', 5.5, 0.3, 0.5, 30, 80, 250, 50, 200, 60]);

  await wb.xlsx.writeFile('tests/test_input.xlsx');
  console.log('test xlsx 已生成：tests/test_input.xlsx');
}

main().catch(e => { console.error(e); process.exit(1); });